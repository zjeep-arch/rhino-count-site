import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
vm.runInNewContext(fs.readFileSync('data.js','utf8'),context);
vm.runInNewContext(fs.readFileSync('profile-folders.js','utf8'),context);
const {RhinoProfile:render,SITE_DATA:data}=context.window;
const html=fs.readFileSync('index.html','utf8');
const profile=render.profile(data);
assert.equal(html.match(/<section id="profile"[^>]*>([\s\S]*?)<\/section>/)[1].trim(),profile.trim(),'Run node scripts/render-profile.mjs');
const keys=['主理人','学历','勋章','履历','关注','能力','坐标','频道'];
assert.deepEqual([...profile.matchAll(/class="pf-front"><b>(.*?)<\/b>/g)].map(x=>x[1]),keys);
assert.equal((profile.match(/data-profile-file="/g)||[]).length,8);
assert(!profile.includes('<video'),'Profile must not contain videos');
assert(!profile.includes('Identity Files'),'No detached Identity Files title');
assert(profile.includes('小红书 · 1147661654'));
assert(profile.includes('href="https://www.xiaohongshu.com/user/profile/60572004000000000101ce41"'));
assert(profile.includes('aria-controls="identity-files"'));
const stress=structuredClone(data);stress.profile.cells[0].v='<script>Test</script>';
assert(render.profile(stress).includes('&lt;script&gt;Test&lt;/script&gt;'));
console.log('PASS: all eight identities in approved order; channel links correctly; no video; static/runtime content match.');
